function escapeHtml(s) {
  const div = document.createElement("div");
  div.textContent = s;
  return div.innerHTML;
}

export function initCasesCarousel(root) {
  const track = root.querySelector("#cases-track");
  const prev = root.querySelector("#cases-prev");
  const next = root.querySelector("#cases-next");
  const counter = root.querySelector("#cases-counter");
  const dotsWrap = root.querySelector("#cases-dots");
  
  // Находим контейнер, высоту которого нужно менять
  const viewport = root.querySelector(".cases__viewport"); 

  if (!track || !prev || !next) return () => {};

  let index = 0;
  const total = CASES.length;

  // Очищаем трек перед добавлением (на случай повторной инициализации)
  track.innerHTML = '';
  if (dotsWrap) dotsWrap.innerHTML = '';

  CASES.forEach((c, i) => {
    const slide = document.createElement("article");
    slide.className = "case-slide";
    slide.setAttribute("aria-hidden", i === 0 ? "false" : "true");
    slide.innerHTML = `
      <h3>${escapeHtml(c.title)}</h3>
      <div class="case-field">
        <span class="case-field__label">Ситуация</span>
        <p class="case-field__text">${escapeHtml(c.situation)}</p>
      </div>
      <div class="case-field">
        <span class="case-field__label">Угроза</span>
        <p class="case-field__text">${escapeHtml(c.threat)}</p>
      </div>
      <div class="case-field">
        <span class="case-field__label">Результат</span>
        <p class="case-field__text">${escapeHtml(c.result)}</p>
      </div>
    `;
    track.appendChild(slide);

    const dot = document.createElement("button");
    dot.type = "button";
    dot.className = "cases__dot" + (i === 0 ? " is-active" : "");
    dot.setAttribute("aria-label", `Кейс ${i + 1}`);
    dot.addEventListener("click", () => goTo(i));
    dotsWrap?.appendChild(dot);
  });

  function update() {
    track.style.transform = `translateX(-${index * 100}%)`;
    
    if (counter) counter.textContent = `${index + 1} / ${total}`;
    
    dotsWrap?.querySelectorAll(".cases__dot").forEach((d, i) => {
      d.classList.toggle("is-active", i === index);
    });
    
    const slides = track.querySelectorAll(".case-slide");
    slides.forEach((el, i) => {
      el.setAttribute("aria-hidden", i === index ? "false" : "true");
    });

    // --- ЛОГИКА АДАПТИВНОЙ ВЫСОТЫ ---
    if (viewport && slides[index]) {
      // Даем браузеру долю секунды на перерисовку (важно для правильных отступов)
      setTimeout(() => {
        const activeHeight = slides[index].offsetHeight;
        viewport.style.height = `${activeHeight}px`;
      }, 10);
    }
  }

  function goTo(i) {
    index = (i + total) % total;
    update();
  }

  prev.addEventListener("click", () => goTo(index - 1));
  next.addEventListener("click", () => goTo(index + 1));

  let touchStartX = 0;
  track.addEventListener(
    "touchstart",
    (e) => {
      touchStartX = e.changedTouches[0].screenX;
    },
    { passive: true }
  );
  
  track.addEventListener(
    "touchend",
    (e) => {
      const dx = e.changedTouches[0].screenX - touchStartX;
      if (Math.abs(dx) > 50) {
        if (dx < 0) goTo(index + 1);
        else goTo(index - 1);
      }
    },
    { passive: true }
  );

  // Вычисляем высоту при загрузке страницы
  // Задержка нужна, чтобы подгрузились шрифты, которые могут менять высоту текста
  setTimeout(() => {
    update();
  }, 150);

  // Пересчитываем высоту при изменении размера окна (например, поворот телефона)
  window.addEventListener('resize', () => {
    update();
  });

  return () => {};
}